_BY_LOWER = {name.lower(): name for name in COUNTRIES}


def canonical_country(value: Optional[str]) -> Optional[str]:
    """The map's spelling of `value` (case-insensitive), None for blank.

    Raises ValueError for a name the map does not know.
    """
    if value is None:
        return None
    cleaned = " ".join(value.split())
    if not cleaned:
        return None
    try:
        return _BY_LOWER[cleaned.lower()]
    except KeyError:
        raise ValueError(f"Unknown country {cleaned!r}; use a name from GET /api/v1/devices/countries") from None
